#!/usr/bin/env node
// Inlines the façade header and sources into one translation unit for the libcascade toolchain.
//
// Why: `customBindings` with `scope: 'main'` concatenates file *contents* into the toolchain's
// embind TU, which is compiled from a scratch directory inside the container, so a relative
// `#include "whittle_kernel.h"` cannot resolve. We therefore hand the toolchain one
// self-contained file. `#line` directives keep compiler diagnostics pointing at the real sources.
//
// Also stamps WREN_BUILD_ID: a content hash of the façade sources, the toolchain config and
// the pinned toolchain version (PLAN §7.2 cache key inputs), reported by kernelInfo().
//
// SPDX-License-Identifier: GPL-3.0-or-later

import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);

const sources = [
  'src/whittle_kernel.h',
  'src/whittle_core.cpp',
  'src/whittle_modeling.cpp',
  'src/whittle_pushpull.cpp',
  'src/whittle_measure.cpp',
  'src/whittle_io.cpp',
  'src/whittle_kernel.cpp',
  'src/whittle_bindings.cpp',
];
const hashed = [...sources, 'libcascade.config.ts', 'scripts/amalgamate.mjs'];

const toolchainVersion = require('@libcascade/toolchain/package.json').version;
const hash = createHash('sha256');
for (const file of hashed) {
  hash.update(`${file}\0`);
  hash.update(readFileSync(join(root, file)));
  hash.update('\0');
}
hash.update(`@libcascade/toolchain@${toolchainVersion}`);
const buildId = hash.digest('hex').slice(0, 16);

const localInclude = /^\s*#\s*include\s+"whittle_kernel\.h"\s*$/;
const pragmaOnce = /^\s*#\s*pragma\s+once\s*$/;

let out = '';
out += '// GENERATED by packages/kernel/scripts/amalgamate.mjs — do not edit.\n';
out += `// Sources: ${sources.join(', ')}\n`;
out += `#define WREN_BUILD_ID "${buildId}"\n`;
for (const file of sources) {
  const lines = readFileSync(join(root, file), 'utf8').split('\n');
  out += `#line 1 "packages/kernel/${file}"\n`;
  for (const line of lines) {
    // Keep line numbering stable: replace dropped lines with blank ones.
    out += localInclude.test(line) || pragmaOnce.test(line) ? '\n' : `${line}\n`;
  }
}

const outDir = join(root, '.libcascade');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'whittle_facade.cpp'), out);
writeFileSync(join(outDir, 'build-id.txt'), `${buildId}\n`);
process.stdout.write(`amalgamate: .libcascade/whittle_facade.cpp (buildId ${buildId})\n`);
