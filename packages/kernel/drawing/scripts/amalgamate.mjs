#!/usr/bin/env node
// Inlines the drawing kernel façade into one translation unit for the libcascade toolchain, like
// ../../scripts/amalgamate.mjs does for the main kernel (`customBindings` with `scope: 'main'`
// concatenates file contents, so relative includes cannot resolve inside the container).
//
// The drawing TU reuses the main kernel's whittle_core.cpp (JSON, errors, `guarded`, the handle
// table) unchanged, plus whittle_kernel.h for the types it declares. Only what the drawing sources
// call is compiled and linked (ADR-090 amendment).
//
// Also stamps WHITTLE_BUILD_ID: a content hash of the sources, this config and script, and the
// pinned toolchain version, reported by drawingInfo().
//
// SPDX-License-Identifier: GPL-3.0-or-later

import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const drawing = join(dirname(fileURLToPath(import.meta.url)), '..');
const kernel = join(drawing, '..');
const require = createRequire(join(kernel, 'package.json'));

/** In TU order, relative to packages/kernel. */
export const DRAWING_SOURCES = [
  'src/whittle_kernel.h',
  'drawing/cpp/wren_drawing.h',
  'src/whittle_core.cpp',
  'drawing/cpp/wren_drawing_geom.cpp',
  'drawing/cpp/wren_drawing_hlr.cpp',
  'drawing/cpp/wren_drawing_api.cpp',
  'drawing/cpp/wren_drawing_bindings.cpp',
];
const hashed = [
  ...DRAWING_SOURCES,
  'drawing/libcascade.config.ts',
  'drawing/scripts/amalgamate.mjs',
];

export function amalgamate() {
  const toolchainVersion = require('@libcascade/toolchain/package.json').version;
  const hash = createHash('sha256');
  for (const file of hashed) {
    hash.update(`${file}\0`);
    hash.update(readFileSync(join(kernel, file)));
    hash.update('\0');
  }
  hash.update(`@libcascade/toolchain@${toolchainVersion}`);
  const buildId = hash.digest('hex').slice(0, 16);

  const localInclude = /^\s*#\s*include\s+"(whittle_kernel|wren_drawing)\.h"\s*$/;
  const pragmaOnce = /^\s*#\s*pragma\s+once\s*$/;

  let out = '';
  out += '// GENERATED by packages/kernel/drawing/scripts/amalgamate.mjs — do not edit.\n';
  out += `// Sources: ${DRAWING_SOURCES.join(', ')}\n`;
  out += `#define WHITTLE_BUILD_ID "${buildId}"\n`;
  // The shared core includes the IGES reader header unless told not to; the drawing build never
  // reads IGES.
  out += '#define WHITTLE_NO_IGES 1\n';
  out += '#define WREN_DRAWING_KERNEL 1\n';
  for (const file of DRAWING_SOURCES) {
    const lines = readFileSync(join(kernel, file), 'utf8').split('\n');
    out += `#line 1 "packages/kernel/${file}"\n`;
    for (const line of lines) {
      out += localInclude.test(line) || pragmaOnce.test(line) ? '\n' : `${line}\n`;
    }
  }
  const outDir = join(drawing, '.libcascade');
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'wren_drawing_facade.cpp'), out);
  writeFileSync(join(outDir, 'build-id.txt'), `${buildId}\n`);
  return { buildId, file: join(outDir, 'wren_drawing_facade.cpp') };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { buildId } = amalgamate();
  process.stdout.write(
    `amalgamate: drawing/.libcascade/wren_drawing_facade.cpp (buildId ${buildId})\n`,
  );
}
