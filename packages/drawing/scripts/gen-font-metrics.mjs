#!/usr/bin/env node
// Generates src/font/osifont-metrics.ts from the pinned Osifont TTF (ADR-091): units per em, cap
// height, ascender/descender and the advance width of every mapped code point, so text layout in
// the worker-safe annotation module never needs the font file. Kerning is not used anywhere (SVG
// sets font-kerning: none; the PDF writer places glyphs by advance), so layout matches every
// renderer. Re-run after updating the font: `pnpm --filter @wren-cad/drawing metrics`.
// SPDX-License-Identifier: GPL-3.0-or-later
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fontPath = join(here, '../assets/fonts/osifont-lgpl3fe.ttf');
const outPath = join(here, '../src/font/osifont-metrics.ts');
const d = new DataView(readFileSync(fontPath).buffer.slice(0));

const tables = {};
const numTables = d.getUint16(4);
for (let i = 0; i < numTables; i++) {
  const o = 12 + 16 * i;
  const tag = String.fromCharCode(
    d.getUint8(o),
    d.getUint8(o + 1),
    d.getUint8(o + 2),
    d.getUint8(o + 3),
  );
  tables[tag] = { offset: d.getUint32(o + 8), length: d.getUint32(o + 12) };
}
const head = tables.head.offset;
const unitsPerEm = d.getUint16(head + 18);
const hhea = tables.hhea.offset;
const ascender = d.getInt16(hhea + 4);
const descender = d.getInt16(hhea + 6);
const numberOfHMetrics = d.getUint16(hhea + 34);
const hmtx = tables.hmtx.offset;
const advance = (gid) => d.getUint16(hmtx + 4 * Math.min(gid, numberOfHMetrics - 1));

// cmap: prefer (3,10) format 12, else (3,1) format 4.
const cmap = tables.cmap.offset;
const map = new Map();
const nSub = d.getUint16(cmap + 2);
let f12 = -1;
let f4 = -1;
for (let i = 0; i < nSub; i++) {
  const p = d.getUint16(cmap + 4 + 8 * i);
  const e = d.getUint16(cmap + 6 + 8 * i);
  const off = cmap + d.getUint32(cmap + 8 + 8 * i);
  const fmt = d.getUint16(off);
  if (p === 3 && e === 10 && fmt === 12) f12 = off;
  if (p === 3 && e === 1 && fmt === 4) f4 = off;
}
if (f12 >= 0) {
  const n = d.getUint32(f12 + 12);
  for (let i = 0; i < n; i++) {
    const g = f12 + 16 + 12 * i;
    const start = d.getUint32(g);
    const end = d.getUint32(g + 4);
    const gid = d.getUint32(g + 8);
    for (let c = start; c <= end; c++) map.set(c, gid + (c - start));
  }
} else if (f4 >= 0) {
  const segX2 = d.getUint16(f4 + 6);
  const ends = f4 + 14;
  const starts = ends + segX2 + 2;
  const deltas = starts + segX2;
  const ranges = deltas + segX2;
  for (let s = 0; s < segX2 / 2; s++) {
    const end = d.getUint16(ends + 2 * s);
    const start = d.getUint16(starts + 2 * s);
    const delta = d.getInt16(deltas + 2 * s);
    const ro = d.getUint16(ranges + 2 * s);
    for (let c = start; c <= end && c !== 0xffff; c++) {
      let gid;
      if (ro === 0) gid = (c + delta) & 0xffff;
      else {
        const at = ranges + 2 * s + ro + 2 * (c - start);
        gid = d.getUint16(at);
        if (gid !== 0) gid = (gid + delta) & 0xffff;
      }
      if (gid !== 0) map.set(c, gid);
    }
  }
}

// Cap height: OS/2 v2+ sCapHeight, else the glyph 'H' yMax.
let capHeight = 0;
const os2 = tables['OS/2'];
if (os2 && d.getUint16(os2.offset) >= 2) capHeight = d.getInt16(os2.offset + 88);
if (!capHeight) {
  const longLoca = d.getInt16(head + 50) === 1;
  const gid = map.get(0x48);
  const loca = tables.loca.offset;
  const at = longLoca ? d.getUint32(loca + 4 * gid) : 2 * d.getUint16(loca + 2 * gid);
  capHeight = d.getInt16(tables.glyf.offset + at + 8);
}

const cps = [...map.keys()].sort((a, b) => a - b);
const runs = [];
for (const cp of cps) {
  const last = runs[runs.length - 1];
  const w = advance(map.get(cp));
  if (last && last[0] + last.length - 1 === cp) last.push(w);
  else runs.push([cp, w]);
}

const body = `/**
 * Generated by scripts/gen-font-metrics.mjs from assets/fonts/osifont-lgpl3fe.ttf. Do not edit.
 * Osifont (LGPL-3.0 with the GPL font exception; ADR-091, docs/DEPENDENCIES.md).
 * \`runs\`: [first code point, advance, advance, …] for contiguous mapped code points, in font units.
 *
 * SPDX-License-Identifier: GPL-3.0-or-later
 */

export const OSIFONT_METRICS = {
  family: 'osifont',
  unitsPerEm: ${unitsPerEm},
  ascender: ${ascender},
  descender: ${descender},
  capHeight: ${capHeight},
  /** Advance of glyph 0 (.notdef), used for unmapped code points. */
  missingAdvance: ${advance(0)},
  runs: ${JSON.stringify(runs)} as readonly (readonly number[])[],
} as const;
`;
writeFileSync(outPath, body);
console.log(
  `wrote ${outPath}: ${cps.length} code points, ${runs.length} runs, capHeight ${capHeight}/${unitsPerEm}`,
);
