#!/usr/bin/env node
// Prepares and guards the site that is force-pushed to the `cloudflare-pages` branch (ADR-082).
//
//   node scripts/cloudflare-dist.mjs [dist] [--max-mib 25] [--worker-out <dir> --worker-name <name>]
//
// 1. Removes `404.html`. GitHub Pages needs it as the SPA fallback; on Cloudflare Pages its mere
//    presence switches off SPA mode (unknown paths would answer 404 with that page), so without it
//    Cloudflare serves `index.html` with status 200 for every unknown path.
// 2. Checks the root-base invariants (`_headers` shipped, manifest start_url/scope/id `/`).
// 3. Fails if any file exceeds Cloudflare's 25 MiB per-file static-asset limit; prints the largest.
// 4. With `--worker-out`, lays the site out for Workers with static assets (ADR-082 amendment,
//    Cloudflare's successor to Pages): `<out>/public/` holds the site and `<out>/wrangler.jsonc`
//    declares an assets-only Worker serving it, `_headers` applied, unknown paths -> index.html.
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

export const MIB = 1024 * 1024;

/** Every file under `dir` with its size in bytes, largest first. */
export function listFiles(dir) {
  const out = [];
  const walk = (d) => {
    for (const entry of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, entry.name);
      if (entry.isDirectory()) walk(p);
      else out.push({ path: relative(dir, p), bytes: statSync(p).size });
    }
  };
  walk(dir);
  return out.sort((a, b) => b.bytes - a.bytes);
}

/** @returns {string[]} problems; empty when the dist is publishable. */
export function checkDist(dir, maxMib = 25) {
  const problems = [];
  for (const f of listFiles(dir)) {
    if (f.bytes > maxMib * MIB)
      problems.push(
        `${f.path} is ${(f.bytes / MIB).toFixed(2)} MiB, over the ${maxMib} MiB Cloudflare Pages per-file limit`,
      );
  }
  if (!existsSync(join(dir, '_headers'))) problems.push('_headers is missing from the build');
  if (!existsSync(join(dir, 'index.html'))) problems.push('index.html is missing from the build');
  const manifest = join(dir, 'manifest.webmanifest');
  if (existsSync(manifest)) {
    const m = JSON.parse(readFileSync(manifest, 'utf8'));
    for (const key of ['start_url', 'scope', 'id'])
      if (m[key] !== '/')
        problems.push(`manifest ${key} is ${JSON.stringify(m[key])}, expected "/"`);
  } else problems.push('manifest.webmanifest is missing from the build');
  return problems;
}

/** Worker names: lower-case letters, digits and dashes, 1-63 characters (Cloudflare's rule). */
export const WORKER_NAME = /^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/;

/** The Wrangler config of the assets-only Worker that serves `./public`. */
export function wranglerConfig(name) {
  if (!WORKER_NAME.test(name))
    throw new Error(`invalid Cloudflare Worker name ${JSON.stringify(name)}`);
  return {
    name,
    // Any past date works for an assets-only Worker; pinned so deploys are reproducible.
    compatibility_date: '2025-09-01',
    assets: {
      directory: './public',
      // The app has no path router: every unknown navigation gets the shell with 200.
      not_found_handling: 'single-page-application',
    },
  };
}

/** Copies the site into `<out>/public` and writes `<out>/wrangler.jsonc`. */
export function writeWorkerBundle(dist, out, name) {
  const config = wranglerConfig(name);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  cpSync(dist, join(out, 'public'), { recursive: true });
  writeFileSync(
    join(out, 'wrangler.jsonc'),
    `// Generated by apps/web/scripts/cloudflare-dist.mjs (ADR-082). Do not edit on this branch.\n${JSON.stringify(config, null, 2)}\n`,
  );
}

function main() {
  const { values, positionals } = parseArgs({
    allowPositionals: true,
    options: {
      'max-mib': { type: 'string', default: '25' },
      'worker-out': { type: 'string' },
      'worker-name': { type: 'string', default: 'wren-cad' },
    },
  });
  const dir = resolve(positionals[0] ?? 'dist');
  const max = Number(values['max-mib']);
  rmSync(join(dir, '404.html'), { force: true });
  console.log('Largest files:');
  for (const f of listFiles(dir).slice(0, 8))
    console.log(`  ${(f.bytes / MIB).toFixed(2).padStart(8)} MiB  ${f.path}`);
  const problems = checkDist(dir, max);
  if (problems.length) {
    for (const p of problems) console.error(`::error::${p}`);
    process.exit(1);
  }
  console.log(`Cloudflare dist OK (${dir}; every file <= ${max} MiB).`);
  if (values['worker-out']) {
    const out = resolve(values['worker-out']);
    writeWorkerBundle(dir, out, values['worker-name']);
    console.log(`Worker bundle for "${values['worker-name']}" written to ${out}.`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
